module main(input bit clk, choose, data);
  wire literal_en = 1'bx;
  wire undriven_en;
  wire [1:0] literal_y = literal_en ? 2'b01 : 2'b10;
  wire [1:0] undriven_y = undriven_en ? 2'b01 : 2'b10;
  literal_can_be_zero: assert property (literal_y != 0);
  undriven_not_zero: assert property (undriven_y != 0);
  consistent: assert property (undriven_y == (undriven_en ? 2'b01 : 2'b10));
  wire conditional_en = choose ? data : 1'bx;
  wire [1:0] conditional_y = conditional_en ? 2'b01 : 2'b10;
  passed_data: assert property (choose |-> conditional_y != 0);
  literal_branch: assert property (!choose |-> conditional_y != 0);
  wire inv = ~literal_en;
  wire force_zero = literal_en & 1'b0;
  wire cancel = literal_en ^ literal_en;
  wire [1:0] inv_y = inv ? 2'b01 : 2'b10;
  inverted_literal: assert property (inv_y != 0);
  controlling_zero: assert property (!force_zero);
  xor_unknown: assert property (!cancel);
  wire [1:0] mixed;
  assign mixed[1] = 1'bx;
  wire [1:0] forwarded = mixed;
  wire [1:0] gap_y = forwarded[0] ? 2'b01 : 2'b10;
  wire [1:0] x_y = forwarded[1] ? 2'b01 : 2'b10;
  tri1 [1:0] pulled = mixed;
  floating_bit: assert property (gap_y != 0);
  explicit_bit: assert property (x_y != 0);
  physical_gap: assert property (pulled[0]);
  ordinary_gap: assert property (forwarded[0]);
  tri [1:0] bus;
  assign bus = choose ? undriven_y : 2'bzz;
  assign bus = 2'bzz;
  driven_bus: assert property (choose |-> bus == undriven_y);
  wire [1:0] bits = {1'b1, 1'bx};
  wire [1:0] truth_y = bits ? 2'b01 : 2'b10;
  wire index_data = bits[literal_en];
  wire case_x = literal_en === 1'bx;
  wire definite_difference = bits == 2'b00;
  wire [1:0] repeated = {2{literal_en}};
  known_true: assert property (truth_y == 2'b01);
  unknown_index: assert property (index_data);
  exact_x: assert property (case_x);
  differing_bit: assert property (!definite_difference);
  repeated_x: assert property (repeated[1] == repeated[0]);
  reg uninitialized;
  wire [1:0] register_y = uninitialized ? 2'b01 : 2'b10;
  initial_value: assert property (register_y != 0);
endmodule
